  on public.petty_cash_budget_history
  for select
  to authenticated
  using (true);

-- Kelola (insert/update/delete): GA/Admin saja - pola SAMA PERSIS dengan
-- petty_cash_barang & pc_approval_templates (lihat
-- petty-cash-barang-setup.sql / pc-approval-templates-access-setup.sql).
drop policy if exists "petty_cash_budget_insert" on public.petty_cash_budget;
create policy "petty_cash_budget_insert"
  on public.petty_cash_budget
  for insert
  to authenticated
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and (p.role = 'admin' or p.department in ('General Affair', 'HRGA-HSE'))
    )
  );

drop policy if exists "petty_cash_budget_update" on public.petty_cash_budget;
create policy "petty_cash_budget_update"
  on public.petty_cash_budget
  for update
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and (p.role = 'admin' or p.department in ('General Affair', 'HRGA-HSE'))
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and (p.role = 'admin' or p.department in ('General Affair', 'HRGA-HSE'))
    )
  );

