-- 0007_chat_admin.sql
--
-- Chat Admin - percakapan user <-> admin IT (/chat-admin,
-- /chat-admin-management).

-- Fitur Chat Admin - percakapan user <-> admin departemen IT, model "ticket
-- ringan": tiap percakapan = 1 topik dengan status, isinya chat bolak-balik.
-- User buka/lihat di /chat-admin, admin IT kelola di /chat-admin-management.
--
--   support_tickets   1 baris = 1 percakapan (topik)
--   support_messages  isi chat per percakapan
--
-- Status percakapan:
--   menunggu  pesan terakhir dari user, menunggu dibalas admin
--   dibalas   pesan terakhir dari admin
--   selesai   ditutup (user/admin). Kalau user kirim pesan lagi -> otomatis
--             balik ke 'menunggu'.
--
-- Semua perubahan tiket lewat RPC SECURITY DEFINER (tidak ada policy
-- INSERT/UPDATE langsung di support_tickets) supaya user tidak bisa ubah
-- kolom yang bukan haknya (status, assigned_to, dst). Pesan di-insert
-- langsung (dijaga RLS), metadata tiket di-update trigger.
--
-- Lampiran di-upload langsung ke storage VPS (prefix `chat-admin/<user_id>/`,
-- lihat lib/uploadDirect.ts), di sini cuma simpan URL + nama + tipe file.
--
-- Butuh: public.is_it_admin() (feedback-setup.sql) dan
-- public.handle_updated_at() (schema awal). Script IDEMPOTENT.

-- ============================================================
-- 1. Tabel
-- ============================================================

create table if not exists public.support_tickets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  -- Snapshot data pengirim saat percakapan dibuat.
  user_nama text,
  user_email text,
  user_department text,
  kategori text not null,
  subjek text not null,
  status text not null default 'menunggu'
    check (status in ('menunggu', 'dibalas', 'selesai')),
  -- Admin IT yang memegang percakapan (diisi otomatis saat admin pertama
  -- kali membalas, atau lewat tombol "Ambil" / "Alihkan").
  assigned_to uuid references public.profiles(id) on delete set null,
  last_message_at timestamptz not null default now(),
  last_message_preview text,
  last_sender_is_admin boolean not null default false,
  -- Penanda "sudah dibaca" - admin dihitung satu tim (inbox bersama).
  user_last_read_at timestamptz not null default now(),
  admin_last_read_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_support_tickets_user
  on public.support_tickets (user_id, last_message_at desc);
create index if not exists idx_support_tickets_status
  on public.support_tickets (status, last_message_at desc);

drop trigger if exists on_support_tickets_updated on public.support_tickets;
create trigger on_support_tickets_updated
  before update on public.support_tickets
  for each row execute function public.handle_updated_at();

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  sender_id uuid references public.profiles(id) on delete set null,
  sender_nama text,
  is_admin boolean not null default false,
  -- Pesan sistem (mis. "ditandai selesai oleh X") - tampil di tengah,
  -- tidak mengubah status tiket.
  is_system boolean not null default false,
  pesan text not null default '',
  lampiran_url text,
  lampiran_nama text,
  lampiran_tipe text,
  created_at timestamptz not null default now(),
  constraint support_messages_not_empty
    check (length(btrim(pesan)) > 0 or lampiran_url is not null),
  constraint support_messages_max_len check (length(pesan) <= 5000)
);

create index if not exists idx_support_messages_ticket
  on public.support_messages (ticket_id, created_at);

-- ============================================================
-- 2. RLS
-- ============================================================

alter table public.support_tickets enable row level security;
alter table public.support_messages enable row level security;

-- Pemilik lihat percakapannya sendiri, admin IT lihat semua.
drop policy if exists "support_tickets_select" on public.support_tickets;
create policy "support_tickets_select"
  on public.support_tickets
  for select
  to authenticated
  using (user_id = auth.uid() or public.is_it_admin());

drop policy if exists "support_tickets_delete_it_admin" on public.support_tickets;
create policy "support_tickets_delete_it_admin"
  on public.support_tickets
  for delete
  to authenticated
  using (public.is_it_admin());

drop policy if exists "support_messages_select" on public.support_messages;
create policy "support_messages_select"
  on public.support_messages
  for select
  to authenticated
  using (
    exists (
      select 1 from public.support_tickets t
      where t.id = ticket_id
        and (t.user_id = auth.uid() or public.is_it_admin())
    )
  );

-- Kirim pesan: hanya ke percakapan yang boleh dilihat, atas nama sendiri,
-- dan bukan pesan sistem. sender_nama/is_admin dipaksa ulang oleh trigger.
drop policy if exists "support_messages_insert" on public.support_messages;
create policy "support_messages_insert"
  on public.support_messages
  for insert
  to authenticated
  with check (
    sender_id = auth.uid()
    and is_system = false
    and exists (
      select 1 from public.support_tickets t
      where t.id = ticket_id
        and (t.user_id = auth.uid() or public.is_it_admin())
    )
  );

-- ============================================================
-- 3. Trigger pesan: isi data pengirim + update metadata tiket
-- ============================================================

create or replace function public.support_messages_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_owner uuid;
begin
  if new.is_system then
    return new;
  end if;

  select user_id into v_owner from public.support_tickets where id = new.ticket_id;

  new.sender_id := auth.uid();
  select nama into new.sender_nama from public.profiles where id = auth.uid();
  -- Admin IT yang chat di percakapannya sendiri tetap dihitung sebagai user.
  new.is_admin := public.is_it_admin() and v_owner is distinct from auth.uid();
  new.created_at := now();
  return new;
end;
$$;

create or replace function public.support_messages_after_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_preview text;
begin
  if new.is_system then
    return null;
  end if;

  v_preview := case
    when length(btrim(new.pesan)) > 0 then left(btrim(new.pesan), 140)
    else '📎 ' || coalesce(new.lampiran_nama, 'Lampiran')
  end;

  update public.support_tickets t set
    last_message_at = new.created_at,
    last_message_preview = v_preview,
    last_sender_is_admin = new.is_admin,
    status = case when new.is_admin then 'dibalas' else 'menunggu' end,
    closed_at = null,
    assigned_to = case
      when new.is_admin then coalesce(t.assigned_to, new.sender_id)
      else t.assigned_to
    end,
    user_last_read_at = case
      when new.is_admin then t.user_last_read_at else new.created_at
    end,
    admin_last_read_at = case
      when new.is_admin then new.created_at else t.admin_last_read_at
    end
  where t.id = new.ticket_id;

  return null;
end;
$$;

drop trigger if exists on_support_messages_before_insert on public.support_messages;
create trigger on_support_messages_before_insert
  before insert on public.support_messages
  for each row execute function public.support_messages_before_insert();

drop trigger if exists on_support_messages_after_insert on public.support_messages;
create trigger on_support_messages_after_insert
  after insert on public.support_messages
  for each row execute function public.support_messages_after_insert();

