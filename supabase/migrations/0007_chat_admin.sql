-- Buat percakapan baru + pesan pertama sekaligus (atomic).
create or replace function public.support_create_ticket(
  p_kategori text,
  p_subjek text,
  p_pesan text,
  p_lampiran_url text default null,
  p_lampiran_nama text default null,
  p_lampiran_tipe text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_ticket_id bigint;
  p record;
begin
  if v_uid is null then
    raise exception 'Not authenticated';
  end if;
  if coalesce(btrim(p_kategori), '') = '' or coalesce(btrim(p_subjek), '') = '' then
    raise exception 'Kategori dan subjek wajib diisi.';
  end if;
  if coalesce(btrim(p_pesan), '') = '' and p_lampiran_url is null then
    raise exception 'Pesan wajib diisi.';
  end if;

  select nama, email, department into p from public.profiles where id = v_uid;

  insert into public.support_tickets
    (user_id, user_nama, user_email, user_department, kategori, subjek)
  values
    (v_uid, p.nama, p.email, p.department, btrim(p_kategori), left(btrim(p_subjek), 150))
  returning id into v_ticket_id;

  insert into public.support_messages
    (ticket_id, sender_id, pesan, lampiran_url, lampiran_nama, lampiran_tipe)
  values
    (v_ticket_id, v_uid, coalesce(p_pesan, ''), p_lampiran_url, p_lampiran_nama, p_lampiran_tipe);

  return v_ticket_id;
end;
$$;

-- Tutup ('selesai') atau buka kembali ('buka') percakapan. Pemilik cuma
-- boleh menutup - membuka kembali cukup dengan kirim pesan. Admin IT boleh
-- keduanya; saat dibuka, status dihitung dari pengirim pesan terakhir.
create or replace function public.support_set_status(
  p_ticket_id bigint,
  p_action text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_is_admin boolean := public.is_it_admin();
  t record;
  v_nama text;
begin
  if p_action not in ('selesai', 'buka') then
    raise exception 'Aksi tidak valid.';
  end if;

  select user_id, status, last_sender_is_admin into t
  from public.support_tickets where id = p_ticket_id;
  if t.user_id is null then
    raise exception 'Percakapan tidak ditemukan.';
  end if;
  if not v_is_admin and not (t.user_id = v_uid and p_action = 'selesai') then
    raise exception 'Tidak diizinkan.';
  end if;
  if (p_action = 'selesai') = (t.status = 'selesai') then
    return;
  end if;

  update public.support_tickets set
    status = case
      when p_action = 'selesai' then 'selesai'
      when t.last_sender_is_admin then 'dibalas'
      else 'menunggu'
    end,
    closed_at = case when p_action = 'selesai' then now() else null end
  where id = p_ticket_id;

  select nama into v_nama from public.profiles where id = v_uid;
  insert into public.support_messages
    (ticket_id, sender_id, sender_nama, is_admin, is_system, pesan)
  values (
    p_ticket_id, v_uid, v_nama, v_is_admin and t.user_id <> v_uid, true,
    coalesce(v_nama, 'Seseorang') || case
      when p_action = 'selesai' then ' menandai percakapan selesai'
      else ' membuka kembali percakapan'
    end
  );
end;
$$;

-- Ambil / alihkan percakapan ke admin IT lain (p_admin_id null = lepas).
create or replace function public.support_assign(
  p_ticket_id bigint,
  p_admin_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_it_admin() then
    raise exception 'Tidak diizinkan.';
  end if;
  if p_admin_id is not null and not exists (
    select 1 from public.profiles
    where id = p_admin_id and role = 'admin' and department = 'IT'
  ) then
    raise exception 'Penerima harus admin departemen IT.';
  end if;

  update public.support_tickets set assigned_to = p_admin_id
  where id = p_ticket_id;
end;
$$;

-- Tandai percakapan sudah dibaca oleh sisi pemanggil.
create or replace function public.support_mark_read(p_ticket_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  update public.support_tickets set user_last_read_at = now()
  where id = p_ticket_id and user_id = v_uid;

  if not found and public.is_it_admin() then
    update public.support_tickets set admin_last_read_at = now()
    where id = p_ticket_id;
  end if;
end;
$$;

-- Angka badge sidebar: user = percakapan dengan balasan admin yang belum
-- dibaca, admin = percakapan berstatus 'menunggu' (perlu dibalas).
create or replace function public.support_badge_counts()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'user_unread', (
      select count(*) from public.support_tickets
      where user_id = auth.uid()
        and last_sender_is_admin
        and last_message_at > user_last_read_at
    ),
    'admin_waiting', case when public.is_it_admin() then (
      select count(*) from public.support_tickets
      where status = 'menunggu' and user_id <> auth.uid()
    ) else 0 end
  );
$$;

revoke all on function public.support_create_ticket(text, text, text, text, text, text) from public;
revoke all on function public.support_set_status(bigint, text) from public;
revoke all on function public.support_assign(bigint, uuid) from public;
revoke all on function public.support_mark_read(bigint) from public;
revoke all on function public.support_badge_counts() from public;
grant execute on function public.support_create_ticket(text, text, text, text, text, text) to authenticated;
grant execute on function public.support_set_status(bigint, text) to authenticated;
grant execute on function public.support_assign(bigint, uuid) to authenticated;
grant execute on function public.support_mark_read(bigint) to authenticated;
grant execute on function public.support_badge_counts() to authenticated;

