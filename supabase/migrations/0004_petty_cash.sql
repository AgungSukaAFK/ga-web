-- Melengkapi Management Petty Cash (admin only) jadi kontrol PENUH A-Z atas
-- seluruh rantai dokumen (Pengajuan -> Voucher -> Sub-Voucher -> Deklarasi),
-- BUKAN cuma override status/approvals (sudah ada, lihat
-- petty-cash-admin-management-setup.sql). Tiga kemampuan baru, semua lewat
-- RPC SECURITY DEFINER (bukan RLS blanket) supaya konsistensi antar dokumen
-- SELALU dijaga otomatis oleh DB, bukan berharap client selalu benar:
--
--  1. HAPUS BERANTAI (`admin_delete_petty_cash_document`) - hapus Pengajuan
--     otomatis ikut menghapus Voucher -> Sub-Voucher -> Deklarasi
--     turunannya, DAN me-refund dana yang sudah ditarik sub-voucher kembali
--     ke `petty_cash_budget.current_budget` (simetris dgn potongannya di
--     create_petty_cash_sub_voucher). Kalau yang dihapus Deklarasi/Voucher
--     saja (bukan dari Pengajuan), status "Selesai" Voucher induk yang
--     sudah tercapai otomatis di-recheck & diturunkan lagi ke "Approved"
--     kalau syaratnya sudah tidak terpenuhi lagi (lihat
--     _pc_admin_recheck_voucher_completion - kebalikan dari trigger
--     handle_petty_cash_deklarasi_complete_voucher,
--     petty-cash-voucher-deklarasi-complete-setup.sql).
--
--  2. GANTI KODE BERANTAI (`admin_rename_petty_cash_kode`) - kalau yang
--     diganti kode_voucher, SEMUA kode_sub_voucher turunannya (format
--     "{kode_voucher}-SV{urutan}") otomatis ikut diganti prefix-nya supaya
--     tetap konsisten (bukan nyisa kode lama yang membingungkan). Dokumen
--     lain (Pengajuan/Deklarasi) tidak perlu ikut berubah karena relasinya
--     ke Voucher/Sub-Voucher SELALU lewat foreign key id (pengajuan_id/
--     voucher_id/sub_voucher_id) - label "kode_pengajuan"/"kode_voucher"
--     yang ditampilkan di dokumen turunan itu SELALU live-join, bukan
--     disalin literal, jadi otomatis ikut ter-update tanpa perlu disentuh.
--
--  3. EDIT PAKSA (`admin_force_update_pengajuan/voucher/deklarasi/
--     sub_voucher`) - admin bisa mengedit item/tanggal/departemen/company/
--     budget/catatan/lampiran dokumen APA PUN, di status APA PUN (beda dari
--     "Edit & Setujui" approver yang cuma bisa dipakai approver yang
--     gilirannya sedang pending). total_amount SELALU dihitung ULANG dari
--     items yang dikirim (bukan dipercaya dari client) - konsistensi harga
--     x qty x total tetap terjaga. Khusus Sub-Voucher: qty/harga BOLEH
--     disesuaikan (item_index & barisnya TIDAK BOLEH ditambah/dihapus -
--     lihat komentar di fungsinya, supaya "sisa qty yang belum ditarik" di
--     create_petty_cash_sub_voucher tetap valid) dan SELISIH nominalnya
--     otomatis disesuaikan ke `petty_cash_budget.current_budget` (bukan
--     dibiarkan nyimpang dari budget yang sudah kepotong).
--
-- Setiap aksi WAJIB menyertakan alasan (`p_reason`) dan tercatat permanen di
-- tabel audit baru `petty_cash_admin_audit_log` (select admin-only, TIDAK
-- ADA policy insert/update/delete - satu-satunya jalan masuk baris baru
-- adalah dari dalam RPC di bawah, supaya log ini genuine/tidak bisa
-- dipalsukan lewat client).
--
-- Jalankan SEKALI lewat SQL Editor Supabase (project utama), SETELAH semua
-- file petty-cash-*-setup.sql lain (termasuk
-- petty-cash-sub-voucher-payment-setup.sql).

-- ============================================================
-- 0. Tabel audit log
-- ============================================================

create table if not exists public.petty_cash_admin_audit_log (
