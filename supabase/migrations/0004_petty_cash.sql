-- Sub-Voucher: BEDA dari 3 lainnya - `p_items` WAJIB punya persis set
-- `item_index` yang sama dgn baris yang sudah ada (tidak boleh
-- tambah/hapus/acak baris), cuma qty/unit_price/note per baris yang boleh
-- disesuaikan admin. Ini supaya "sisa qty yang belum ditarik" yang dihitung
-- create_petty_cash_sub_voucher (dari petty_cash_voucher.items dikurangi
-- SEMUA sub-voucher yang match item_index yang sama) tetap valid - kalau
-- item_index bebas diubah, perhitungan itu bisa jadi salah/hitungan ganda.
-- SELISIH nominal (amount baru - lama) otomatis disesuaikan ke
-- petty_cash_budget.current_budget Voucher induknya - supaya budget yang
-- sudah kepotong saat tarikan tetap match dgn nominal final Sub-Voucher ini
-- (naik = potong lagi selisihnya, gagal kalau sisa budget tidak cukup;
-- turun = refund selisihnya).
create or replace function public.admin_force_update_sub_voucher(
  p_id bigint,
  p_items jsonb,
  p_notes text,
  p_status text,
  p_payment_proof jsonb,
  p_reason text
)
returns public.petty_cash_sub_voucher
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
  v_old public.petty_cash_sub_voucher%rowtype;
  v_row public.petty_cash_sub_voucher%rowtype;
  v_voucher public.petty_cash_voucher%rowtype;
  v_new_amount numeric;
  v_delta numeric;
  v_new_budget numeric;
  v_old_indexes int[];
  v_new_indexes int[];
begin
  select role into v_role from public.profiles where id = auth.uid();
  if v_role is distinct from 'admin' then
    raise exception 'Hanya admin yang boleh melakukan edit paksa Sub-Voucher.';
  end if;
  if p_reason is null or trim(p_reason) = '' then
    raise exception 'Alasan edit paksa wajib diisi.';
  end if;
  if p_status not in ('Menunggu Pembayaran', 'Selesai') then
    raise exception 'Status tidak valid: %', p_status;
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Minimal harus ada 1 barang.';
  end if;

  select * into v_old from public.petty_cash_sub_voucher where id = p_id for update;
  if not found then
    raise exception 'Sub-Voucher tidak ditemukan.';
  end if;

  select array_agg((elem->>'item_index')::int order by (elem->>'item_index')::int)
  into v_old_indexes from jsonb_array_elements(v_old.items) elem;
  select array_agg((elem->>'item_index')::int order by (elem->>'item_index')::int)
  into v_new_indexes from jsonb_array_elements(p_items) elem;

  if v_new_indexes is distinct from v_old_indexes then
    raise exception 'Baris barang tidak boleh ditambah/dihapus - admin cuma bisa menyesuaikan qty/harga baris yang sudah ada.';
  end if;

  select coalesce(sum(((elem->>'qty')::numeric) * ((elem->>'unit_price')::numeric)), 0)
  into v_new_amount
  from jsonb_array_elements(p_items) elem;

  v_delta := v_new_amount - v_old.amount;

  select * into v_voucher from public.petty_cash_voucher where id = v_old.voucher_id for update;

  if v_delta <> 0 and v_voucher.budget_id is not null then
    update public.petty_cash_budget
    set current_budget = current_budget - v_delta
    where id = v_voucher.budget_id
      and (v_delta <= 0 or current_budget >= v_delta)
    returning current_budget into v_new_budget;

    if v_new_budget is null then
      raise exception 'Sisa budget departemen tidak mencukupi untuk kenaikan nominal ini.';
    end if;

    insert into public.petty_cash_budget_history (
      budget_id, ref_type, ref_id, user_id, change_amount, previous_budget, new_budget, description
    ) values (
      v_voucher.budget_id, 'adjustment', v_old.id, auth.uid(), -v_delta,
      v_new_budget + v_delta, v_new_budget,
      'Edit paksa admin Sub-Voucher ' || v_old.kode_sub_voucher || ' - alasan: ' || p_reason
    );
  end if;

  update public.petty_cash_sub_voucher
  set items = p_items,
      amount = v_new_amount,
      notes = p_notes,
      status = p_status,
      payment_proof = coalesce(p_payment_proof, payment_proof),
      updated_at = now()
  where id = p_id
  returning * into v_row;

  perform public._pc_admin_recheck_voucher_completion(v_old.voucher_id);

  insert into public.petty_cash_admin_audit_log (
    admin_id, action, doc_type, doc_id, kode, reason, detail
  ) values (
    auth.uid(), 'force_edit', 'sub_voucher', p_id, v_row.kode_sub_voucher, p_reason,
    jsonb_build_object(
      'amount_lama', v_old.amount, 'amount_baru', v_new_amount, 'status_baru', p_status
    )
  );

  return v_row;
end;
