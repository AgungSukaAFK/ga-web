  action text not null, -- 'delete' | 'rename_kode' | 'force_edit'
  doc_type text not null, -- 'pengajuan' | 'voucher' | 'sub_voucher' | 'deklarasi'
  doc_id bigint not null,
  kode text,
  reason text not null,
  detail jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists idx_petty_cash_admin_audit_log_doc
  on public.petty_cash_admin_audit_log (doc_type, doc_id);
