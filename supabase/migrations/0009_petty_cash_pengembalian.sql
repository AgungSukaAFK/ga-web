-- 0009_petty_cash_pengembalian.sql
--
-- Tiga perubahan di ujung alur Petty Cash (tarikan dana -> Deklarasi):
--
--  1. DEKLARASI BOLEH DIAJUKAN ULANG SETELAH DITOLAK. Dulu unique
--     (sub_voucher_id) mutlak, jadi begitu Deklarasi pertama ditolak tarikan
--     itu buntu (cuma bisa lewat admin). Sekarang yang unik cuma Deklarasi
--     yang MASIH AKTIF (status selain 'Rejected') - satu tarikan tetap
--     paling banyak punya 1 Deklarasi aktif, yang ditolak tinggal jadi
--     riwayat.
--
--  2. TOTAL DEKLARASI TIDAK BOLEH MELEBIHI NOMINAL TARIKAN (dikurangi dana
--     yang sudah dikembalikan, lihat no. 3). Dijaga trigger supaya berlaku
--     juga utk "Edit & Setujui" approver & edit paksa admin, bukan cuma
--     form requester. Kelebihan pemakaian diurus di luar sistem / lewat
--     tarikan baru.
--
--  3. PENGEMBALIAN DANA LEBIH (tabel baru `petty_cash_pengembalian`). Kalau
--     Deklarasi yang disetujui lebih kecil dari nominal tarikan, requester
--     bisa mengajukan pengembalian sisa (wajib bukti setor/transfer). Budget
--     baru bertambah lagi setelah Finance approver (department Finance +
--     role approver, atau admin) mengkonfirmasi uangnya sudah diterima -
--     kebalikan dari mark_petty_cash_sub_voucher_paid. Pengembalian TIDAK
--     ikut syarat Voucher "Selesai" maupun syarat bikin Pengajuan baru -
--     tarikan dianggap tuntas begitu Deklarasi-nya disetujui.
--
-- Jalankan SEKALI lewat SQL Editor Supabase (project utama), SETELAH
-- 0004_petty_cash.sql. Script IDEMPOTENT.

-- ============================================================
-- 1. Deklarasi ulang setelah ditolak
-- ============================================================

alter table public.petty_cash_deklarasi
  drop constraint if exists petty_cash_deklarasi_sub_voucher_id_key;

-- Nama index ini dicek createDeklarasiFromSubVoucher
-- (services/pettyCashDeklarasiService.ts) utk pesan error yang jelas.
create unique index if not exists petty_cash_deklarasi_sub_voucher_active_key
  on public.petty_cash_deklarasi (sub_voucher_id)
  where status <> 'Rejected';

-- Index unique lama ikut hilang bersama constraint-nya - join
-- sub-voucher -> deklarasi tetap butuh index biasa.
create index if not exists idx_petty_cash_deklarasi_sub_voucher_id
  on public.petty_cash_deklarasi (sub_voucher_id);

-- ============================================================
-- 2. Tabel Pengembalian Dana Lebih
-- ============================================================

create table if not exists public.petty_cash_pengembalian (
  id bigint generated by default as identity primary key,
  -- "{kode_sub_voucher}-PGB{urutan}", digenerate di dalam
  -- create_petty_cash_pengembalian (bukan dari client).
  kode_pengembalian text not null unique,
  sub_voucher_id bigint not null references public.petty_cash_sub_voucher(id) on delete cascade,
  -- Denormalisasi dari sub_voucher.voucher_id - dipakai cari budget_id saat
  -- konfirmasi & filter company di antrian Finance.
  voucher_id bigint not null references public.petty_cash_voucher(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric not null check (amount > 0),
  notes text,
  -- Bukti setor/transfer balik dari requester - wajib (dicek di RPC).
  attachments jsonb not null default '[]',
  -- 'Menunggu Konfirmasi' -> 'Selesai' (dikonfirmasi Finance, budget
  -- bertambah) atau 'Ditolak' (uang belum diterima / tidak sesuai).
  status text not null default 'Menunggu Konfirmasi',
  reject_reason text,
  processed_at timestamptz,
  processed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  created_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id) on delete set null
);

create index if not exists idx_petty_cash_pengembalian_sub_voucher_id
  on public.petty_cash_pengembalian (sub_voucher_id);
create index if not exists idx_petty_cash_pengembalian_user_id
  on public.petty_cash_pengembalian (user_id);
create index if not exists idx_petty_cash_pengembalian_status
  on public.petty_cash_pengembalian (status);

create or replace function public.handle_petty_cash_pengembalian_audit()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.updated_by := auth.uid();
    new.created_at := now();
    new.updated_at := now();
  elsif tg_op = 'UPDATE' then
    new.created_at := old.created_at;
    new.created_by := old.created_by;
    new.updated_at := now();
    new.updated_by := auth.uid();
  end if;
  return new;
end;
$$;

drop trigger if exists on_petty_cash_pengembalian_write on public.petty_cash_pengembalian;
create trigger on_petty_cash_pengembalian_write
  before insert or update on public.petty_cash_pengembalian
  for each row execute function public.handle_petty_cash_pengembalian_audit();

alter table public.petty_cash_pengembalian enable row level security;

