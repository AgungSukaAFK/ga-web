-- ============================================================
-- 3. Batas total Deklarasi
-- ============================================================

create or replace function public.check_petty_cash_deklarasi_total()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_amount numeric;
  v_returned numeric;
begin
  if new.sub_voucher_id is null or new.status = 'Rejected' then
    return new;
  end if;
  -- Update yang tidak mengubah total (approve/reject biasa) dilewati, supaya
  -- data lama yang kebetulan sudah melebihi batas tetap bisa diproses.
  if tg_op = 'UPDATE' and new.total_amount is not distinct from old.total_amount then
    return new;
  end if;

  -- Lock baris tarikan supaya tidak balapan dgn create_petty_cash_pengembalian.
  select amount into v_amount
  from public.petty_cash_sub_voucher
  where id = new.sub_voucher_id
  for update;

  select coalesce(sum(amount), 0) into v_returned
  from public.petty_cash_pengembalian
  where sub_voucher_id = new.sub_voucher_id
    and status <> 'Ditolak';

  if new.total_amount + v_returned > v_amount then
    raise exception 'Total Deklarasi (Rp %) melebihi nominal tarikan (Rp %)%.',
      replace(to_char(new.total_amount, 'FM999,999,999,990'), ',', '.'),
      replace(to_char(v_amount, 'FM999,999,999,990'), ',', '.'),
      case when v_returned > 0
        then ' dikurangi dana yang sudah dikembalikan (Rp '
          || replace(to_char(v_returned, 'FM999,999,999,990'), ',', '.') || ')'
        else '' end;
  end if;

  return new;
end;
$$;

drop trigger if exists on_petty_cash_deklarasi_check_total on public.petty_cash_deklarasi;
create trigger on_petty_cash_deklarasi_check_total
  before insert or update of total_amount on public.petty_cash_deklarasi
  for each row execute function public.check_petty_cash_deklarasi_total();

-- ============================================================
-- 4. RPC Pengembalian
-- ============================================================

-- Requester mengajukan pengembalian sisa dana satu tarikan. Sisa = nominal
-- tarikan - total Deklarasi yang disetujui - pengembalian lain yang belum
-- ditolak. Boleh sebagian, boleh beberapa kali selama total <= sisa.
create or replace function public.create_petty_cash_pengembalian(
  p_sub_voucher_id bigint,
  p_amount numeric,
  p_notes text,
  p_attachments jsonb
)
returns public.petty_cash_pengembalian
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sv public.petty_cash_sub_voucher%rowtype;
  v_declared numeric;
  v_returned numeric;
  v_sisa numeric;
  v_seq int;
  v_row public.petty_cash_pengembalian%rowtype;
begin
  select * into v_sv
  from public.petty_cash_sub_voucher
  where id = p_sub_voucher_id
  for update;

  if not found then
    raise exception 'Sub-Voucher tidak ditemukan.';
  end if;
  if v_sv.user_id <> auth.uid() then
    raise exception 'Anda bukan pemilik Sub-Voucher ini.';
  end if;
  if v_sv.status <> 'Selesai' then
    raise exception 'Tarikan ini belum dibayar Finance, belum ada dana yang bisa dikembalikan.';
  end if;

  -- Paling banyak 1 Deklarasi Approved per tarikan (lihat index
  -- petty_cash_deklarasi_sub_voucher_active_key di atas).
  select total_amount into v_declared
  from public.petty_cash_deklarasi
  where sub_voucher_id = p_sub_voucher_id
    and status = 'Approved';

  if v_declared is null then
    raise exception 'Deklarasi tarikan ini belum disetujui - sisa dana baru bisa dikembalikan setelah Deklarasi disetujui.';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Nominal pengembalian harus lebih dari 0.';
  end if;
  if p_attachments is null or jsonb_typeof(p_attachments) <> 'array' or jsonb_array_length(p_attachments) = 0 then
    raise exception 'Bukti setor/transfer pengembalian wajib dilampirkan.';
  end if;

  select coalesce(sum(amount), 0) into v_returned
  from public.petty_cash_pengembalian
  where sub_voucher_id = p_sub_voucher_id
    and status <> 'Ditolak';

  v_sisa := v_sv.amount - v_declared - v_returned;
  if p_amount > v_sisa then
    raise exception 'Nominal pengembalian melebihi sisa dana tarikan (sisa Rp %).',
      replace(to_char(greatest(v_sisa, 0), 'FM999,999,999,990'), ',', '.');
  end if;

  -- Dihitung setelah lock baris tarikan di atas, jadi aman dari 2 pengajuan
  -- bersamaan utk tarikan yang sama.
  select count(*) + 1 into v_seq
  from public.petty_cash_pengembalian
  where sub_voucher_id = p_sub_voucher_id;

  insert into public.petty_cash_pengembalian (
    kode_pengembalian, sub_voucher_id, voucher_id, user_id, amount, notes, attachments
  ) values (
    v_sv.kode_sub_voucher || '-PGB' || v_seq, v_sv.id, v_sv.voucher_id, auth.uid(),
    p_amount, nullif(trim(coalesce(p_notes, '')), ''), p_attachments
  )
  returning * into v_row;

  return v_row;
end;
$$;

grant execute on function public.create_petty_cash_pengembalian(bigint, numeric, text, jsonb) to authenticated;

-- Finance mengkonfirmasi uang pengembalian sudah diterima -> budget
-- Voucher-nya bertambah sebesar nominal pengembalian.
create or replace function public.confirm_petty_cash_pengembalian(
  p_id bigint
)
returns public.petty_cash_pengembalian
language plpgsql
security definer
set search_path = public
as $$
declare
  v_department text;
  v_role text;
  v_row public.petty_cash_pengembalian%rowtype;
  v_budget_id bigint;
  v_kode_sub_voucher text;
  v_new_budget numeric;
begin
  select department, role into v_department, v_role
  from public.profiles where id = auth.uid();

  if not (
    v_role = 'admin'
    or (v_department = 'Finance' and v_role = 'approver')
  ) then
    raise exception 'Anda tidak berwenang mengkonfirmasi pengembalian dana Petty Cash.';
  end if;

  update public.petty_cash_pengembalian
  set status = 'Selesai',
      processed_at = now(),
      processed_by = auth.uid()
  where id = p_id
    and status = 'Menunggu Konfirmasi'
  returning * into v_row;

  if v_row.id is null then
    raise exception 'Pengembalian tidak ditemukan atau sudah diproses.';
  end if;

  select budget_id into v_budget_id
  from public.petty_cash_voucher
  where id = v_row.voucher_id;

  if v_budget_id is null then
    raise exception 'Voucher pengembalian ini tidak punya Budget - hubungi GA/Admin.';
  end if;

  select kode_sub_voucher into v_kode_sub_voucher
  from public.petty_cash_sub_voucher
  where id = v_row.sub_voucher_id;

  update public.petty_cash_budget
  set current_budget = current_budget + v_row.amount
  where id = v_budget_id
  returning current_budget into v_new_budget;

  -- ref_id = id Sub-Voucher (bukan id pengembalian), sama seperti
  -- 'deduction'/'refund' - riwayat budget di halaman Budgeting me-resolve
  -- ref_id ke dokumen Sub-Voucher (loadPcBudgetHistory,
  -- PettyCashBudgetingClient.tsx).
  insert into public.petty_cash_budget_history (
    budget_id, ref_type, ref_id, user_id, change_amount, previous_budget, new_budget, description
  ) values (
    v_budget_id, 'pengembalian', v_row.sub_voucher_id, auth.uid(), v_row.amount,
    v_new_budget - v_row.amount, v_new_budget,
    'Pengembalian dana lebih ' || v_row.kode_pengembalian
      || ' (Sub-Voucher ' || v_kode_sub_voucher || ')'
  );

  return v_row;
end;
$$;

grant execute on function public.confirm_petty_cash_pengembalian(bigint) to authenticated;

-- Finance menolak pengembalian (uang belum diterima / nominal tidak sesuai)
-- - budget tidak berubah, requester bisa mengajukan ulang.
create or replace function public.reject_petty_cash_pengembalian(
  p_id bigint,
  p_reason text
)
returns public.petty_cash_pengembalian
language plpgsql
security definer
set search_path = public
as $$
declare
  v_department text;
  v_role text;
  v_row public.petty_cash_pengembalian%rowtype;
begin
  select department, role into v_department, v_role
  from public.profiles where id = auth.uid();

  if not (
    v_role = 'admin'
    or (v_department = 'Finance' and v_role = 'approver')
  ) then
    raise exception 'Anda tidak berwenang menolak pengembalian dana Petty Cash.';
  end if;
  if p_reason is null or trim(p_reason) = '' then
    raise exception 'Alasan penolakan wajib diisi.';
  end if;

  update public.petty_cash_pengembalian
  set status = 'Ditolak',
      reject_reason = trim(p_reason),
      processed_at = now(),
      processed_by = auth.uid()
  where id = p_id
    and status = 'Menunggu Konfirmasi'
  returning * into v_row;

  if v_row.id is null then
    raise exception 'Pengembalian tidak ditemukan atau sudah diproses.';
  end if;

  return v_row;
end;
$$;

grant execute on function public.reject_petty_cash_pengembalian(bigint, text) to authenticated;

-- ============================================================
-- 5. Hapus Sub-Voucher oleh admin - sesuaikan dgn no. 1 & 3
-- ============================================================

-- REPLACES versi di 0004_petty_cash.sql (asal:
-- petty_cash_admin_full_management_setup.sql). Dua perubahan:
--  - Deklarasi per tarikan sekarang bisa lebih dari 1 baris (yang ditolak +
--    pengajuan ulangnya) - SEMUA dihapus, bukan cuma 1.
--  - Pengembalian yang sudah dikonfirmasi Finance sudah menambah budget,
--    jadi yang di-refund cuma sisanya (nominal tarikan - pengembalian
--    'Selesai'), supaya budget tidak bertambah dua kali.
create or replace function public._pc_admin_refund_sub_voucher(
  p_sub_voucher_id bigint,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sv public.petty_cash_sub_voucher%rowtype;
  v_voucher public.petty_cash_voucher%rowtype;
  v_deklarasi_ids bigint[];
  v_deklarasi_kode text;
  v_returned numeric;
  v_refund numeric;
  v_new_budget numeric;
begin
  select * into v_sv from public.petty_cash_sub_voucher where id = p_sub_voucher_id for update;
  if not found then
    raise exception 'Sub-Voucher tidak ditemukan.';
  end if;

  select * into v_voucher from public.petty_cash_voucher where id = v_sv.voucher_id for update;

  -- Hapus dulu supaya FK petty_cash_deklarasi.sub_voucher_id (on delete
  -- restrict) tidak menghalangi hapus Sub-Voucher-nya sendiri di bawah.
  select array_agg(id order by id), string_agg(kode_deklarasi, ', ' order by id)
  into v_deklarasi_ids, v_deklarasi_kode
  from public.petty_cash_deklarasi where sub_voucher_id = p_sub_voucher_id;

  delete from public.petty_cash_deklarasi where sub_voucher_id = p_sub_voucher_id;

  select coalesce(sum(amount), 0) into v_returned
  from public.petty_cash_pengembalian
  where sub_voucher_id = p_sub_voucher_id
    and status = 'Selesai';

  -- Baris pengembalian ikut terhapus lewat FK on delete cascade.
  v_refund := v_sv.amount - v_returned;

  if v_voucher.budget_id is not null and v_refund > 0 then
    update public.petty_cash_budget
    set current_budget = current_budget + v_refund
    where id = v_voucher.budget_id
    returning current_budget into v_new_budget;

    insert into public.petty_cash_budget_history (
      budget_id, ref_type, ref_id, user_id, change_amount, previous_budget, new_budget, description
    ) values (
      v_voucher.budget_id, 'refund', v_sv.id, auth.uid(), v_refund,
      v_new_budget - v_refund, v_new_budget,
      'Refund penghapusan Sub-Voucher ' || v_sv.kode_sub_voucher || ' oleh admin - alasan: ' || p_reason
    );
  end if;

  delete from public.petty_cash_sub_voucher where id = p_sub_voucher_id;

  perform public._pc_admin_recheck_voucher_completion(v_sv.voucher_id);

  return jsonb_build_object(
    'sub_voucher_id', v_sv.id,
    'sub_voucher_kode', v_sv.kode_sub_voucher,
    'refunded_amount', greatest(v_refund, 0),
    'deklarasi_id', v_deklarasi_ids[array_upper(v_deklarasi_ids, 1)],
    'deklarasi_ids', to_jsonb(coalesce(v_deklarasi_ids, '{}')),
    'deklarasi_kode', v_deklarasi_kode
  );
end;
$$;

revoke execute on function public._pc_admin_refund_sub_voucher(bigint, text) from public;
