-- Fitur Feedback - sebelumnya feedback dikirim lewat email (SMTP, lihat
-- api/v1/send-email) dan TIDAK disimpan di mana pun. Sekarang disimpan ke
-- tabel `feedbacks` dan dibaca lewat halaman /feedback-management yang khusus
-- admin departemen IT.
--
-- Lampiran di-upload langsung ke storage VPS (prefix `feedback/<user_id>/`,
-- lihat lib/uploadDirect.ts), di sini cuma simpan URL + nama file aslinya.
--
-- Jalankan SEKALI lewat SQL Editor Supabase (project utama). Butuh
-- `public.handle_updated_at()` (trigger generic, sudah ada dari schema awal).

-- ============================================================
-- 1. Helper: admin departemen IT
-- ============================================================
-- Harus sama dengan isITAdmin() di lib/constants/departments.ts.

create or replace function public.is_it_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'admin' and p.department = 'IT'
  );
$$;

grant execute on function public.is_it_admin() to authenticated;

-- ============================================================
-- 2. Tabel feedbacks
-- ============================================================

create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  user_id uuid default auth.uid() references public.profiles(id) on delete set null,
  -- Snapshot data pengirim saat feedback dikirim (nama/departemen bisa
  -- berubah atau user dihapus belakangan).
  user_nama text,
  user_email text,
  user_department text,
  whatsapp text not null,
  kategori text not null,
  -- HTML dari editor Tiptap di halaman /feedback. Dirender ulang lewat Tiptap
  -- read-only (bukan dangerouslySetInnerHTML) supaya tag di luar schema
  -- editor otomatis terbuang.
  pesan text not null,
  lampiran_url text,
  lampiran_nama text,
  status text not null default 'baru'
    check (status in ('baru', 'diproses', 'selesai')),
  -- Catatan internal tim IT (tidak terlihat oleh pengirim di UI).
  catatan_admin text,
  handled_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_feedbacks_created_at
  on public.feedbacks (created_at desc);
create index if not exists idx_feedbacks_status
  on public.feedbacks (status);

drop trigger if exists on_feedbacks_updated on public.feedbacks;
create trigger on_feedbacks_updated
  before update on public.feedbacks
  for each row execute function public.handle_updated_at();

alter table public.feedbacks enable row level security;

-- User login boleh kirim feedback atas namanya sendiri, status awal 'baru'.
drop policy if exists "feedbacks_insert_own" on public.feedbacks;
create policy "feedbacks_insert_own"
  on public.feedbacks
  for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and status = 'baru'
    and catatan_admin is null
    and handled_by is null
  );

-- Pengirim bisa lihat feedback miliknya, admin IT bisa lihat semua.
drop policy if exists "feedbacks_select" on public.feedbacks;
create policy "feedbacks_select"
  on public.feedbacks
  for select
  to authenticated
  using (user_id = auth.uid() or public.is_it_admin());

drop policy if exists "feedbacks_update_it_admin" on public.feedbacks;
create policy "feedbacks_update_it_admin"
  on public.feedbacks
  for update
  to authenticated
  using (public.is_it_admin())
  with check (public.is_it_admin());

drop policy if exists "feedbacks_delete_it_admin" on public.feedbacks;
create policy "feedbacks_delete_it_admin"
  on public.feedbacks
  for delete
  to authenticated
  using (public.is_it_admin());
